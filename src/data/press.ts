/** 倒序（新→旧），页面渲染统一用这个 */
export const PRESS_SORTED: PressItem[] = [...PRESS].sort((a, b) => (a.date < b.date ? 1 : -1));

/** 按年份分组，保持倒序 */
export function groupByYear(items: PressItem[]) {
  const map = new Map<string, PressItem[]>();
  for (const it of items) {
    const y = it.date.slice(0, 4);
    if (!map.has(y)) map.set(y, []);
    map.get(y)!.push(it);
  }
  return [...map.entries()].map(([year, list]) => ({ year, list }));
}

/** 显示用日期：2024-07-02 → 07.02；2024-07 → 07（同年分组下省略年份） */
export function dayLabel(date: string) {
  const parts = date.split('-');
  return parts.length === 3 ? `${parts[1]}.${parts[2]}` : parts[1];
}
