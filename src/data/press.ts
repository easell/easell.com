/** 倒序（新→旧），页面渲染统一用这个 */
export const PRESS_SORTED: PressItem[] = [...PRESS].sort((a, b) => (a.date < b.date ? 1 : -1));

/** slug → 条目，详情页与内部链接用 */
export const PRESS_BY_SLUG: Map<string, PressItem> = new Map(PRESS_SORTED.map((it) => [it.slug, it]));

/** 上一篇（更早）/ 下一篇（更新），供详情页做站内串联 */
export function pressNeighbors(slug: string) {
  const i = PRESS_SORTED.findIndex((it) => it.slug === slug);
  if (i < 0) return { newer: undefined, older: undefined };
  return { newer: PRESS_SORTED[i - 1], older: PRESS_SORTED[i + 1] };
}

/** 按年份分组，保持倒序 */
export function groupByYear(items: PressItem[]) {
  const map = new Map<string, PressItem[]>();
  for (const it of items) {
    const y = it.date.slice(0, 4);
    if (!map.has(y)) map.set(y, []);
    map.get(y)!.push(it);
  }
  return [...map.entries()].map(([year, list]) => ({ year, list }));
}

/** 显示用日期：2024-07-02 → 07.02；2024-07 → 07（同年分组下省略年份） */
export function dayLabel(date: string) {
  const parts = date.split('-');
  return parts.length === 3 ? `${parts[1]}.${parts[2]}` : parts[1];
}

/** 详情页显示用完整日期：2024-07-02 → 2024 年 7 月 2 日；2024-07 → 2024 年 7 月 */
export function fullDate(date: string) {
  const [y, m, d] = date.split('-');
  return d ? `${y} 年 ${Number(m)} 月 ${Number(d)} 日` : `${y} 年 ${Number(m)} 月`;
}

/** schema.org 用的 ISO 日期（月份补齐到 01） */
export function isoDate(date: string) {
  return date.length === 7 ? `${date}-01` : date;
}
